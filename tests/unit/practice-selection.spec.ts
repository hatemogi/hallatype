import { 다음미완료편 } from '@/practice-selection';

it('현재 편 다음부터 완료 기록을 건너뛰고 미완료 편을 고른다', () => {
  const 완료 = new Set(['0:0', '0:1', '1:0', '2:0']);
  const 다음 = (지문번호: number, 편번호: number) => 완료.has(`${지문번호}:${편번호}`);
  expect(다음미완료편([2, 2, 2], 다음, { 지문번호: 0, 편번호: 0 }))
    .toEqual({ 지문번호: 1, 편번호: 1 });
  expect(다음미완료편([2, 2, 2], 다음, { 지문번호: 2, 편번호: 1 }))
    .toEqual({ 지문번호: 1, 편번호: 1 });
});

it('처음 열 때는 첫 미완료 편을, 전부 완료했으면 없음을 돌려준다', () => {
  const 완료 = (지문번호: number, 편번호: number) => 지문번호 === 0 || 편번호 === 0;
  expect(다음미완료편([2, 2], 완료)).toEqual({ 지문번호: 1, 편번호: 1 });
  expect(다음미완료편([2, 2], () => true, { 지문번호: 1, 편번호: 1 })).toBeNull();
  expect(다음미완료편([], () => false)).toBeNull();
});
