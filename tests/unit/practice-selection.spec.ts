import { 테마별지문들, type 연습지문 } from '@/practice-passages';
import { 다음미완료지문, 첫진입지문선택, 주제지문선택, 주제완료현황,
  지문모음선택, 지문모음완료현황, 마지막지문읽기, 마지막지문저장, 마지막지문저장키 } from '@/practice-selection';
import { 본문버전, 시도목록, 시도시작, 시도완료, 입력묶음, 지문재개시도, type 진행작업 } from '@/practice-progress';

function 선택저장소() {
  const 값들 = new Map<string, string>();
  return {
    getItem: (키: string) => 값들.get(키) ?? null,
    setItem: (키: string, 값: string) => { 값들.set(키, 값); },
  };
}

const 시각 = (시: number, 분: number) =>
  `2026-10-24T${String(시).padStart(2, '0')}:${String(분).padStart(2, '0')}:00.000Z`;

function 시도(지문: 연습지문, 시: number, 완료 = false, 버전 = 본문버전(지문.본문)): 진행작업[] {
  const 시작 = { ...시도시작(지문.id, '2026-10-24', 버전), at: 시각(시, 0) };
  const 입력 = { ...입력묶음(시작.attemptId, 0, [{ code: 'KeyR', shift: false }], 100),
    at: 시각(시, 1) };
  return 완료 ? [시작, 입력, { ...시도완료(시작.attemptId, 200, 2, 2), at: 시각(시, 2) }]
    : [시작, 입력];
}

it('기록이 없거나 본문 버전이 다른 기록뿐이면 시작하기 첫 글에서 시작한다', () => {
  const 첫글 = 테마별지문들.시작하기[0];
  const 기본 = { 테마: '시작하기', 지문: 첫글 };
  expect(첫진입지문선택([])).toEqual(기본);
  expect(첫진입지문선택(시도목록(시도(첫글, 9, true, 'old-version')))).toEqual(기본);
});

it('첫 진입에는 주제를 넘어 가장 최근에 진행 중인 글을 연다', () => {
  const 이른글 = 테마별지문들.시작하기[1];
  const 최근글 = 테마별지문들.명상[3];
  const 기록 = 시도목록([...시도(이른글, 9), ...시도(최근글, 11)]);
  expect(첫진입지문선택(기록)).toEqual({ 테마: '명상', 지문: 최근글 });
});

it('입력하지 않고 선택만 한 글도 저장하고 이전 입력 기록보다 먼저 복원한다', () => {
  const 저장소 = 선택저장소();
  const 입력한글 = 테마별지문들.시작하기[1];
  const 선택한글 = 테마별지문들.명상[3];
  const 기록 = 시도목록(시도(입력한글, 9));
  expect(마지막지문저장(선택한글.id, 저장소)).toBe(true);
  expect(첫진입지문선택(기록, 마지막지문읽기(저장소)))
    .toEqual({ 테마: '명상', 지문: 선택한글 });
  expect(기록).toHaveLength(1);
  expect(지문재개시도(기록, 입력한글.id, 본문버전(입력한글.본문))?.입력들).toHaveLength(1);
});

it('완료 후 다음 글로 이동하면 입력 없이 새로고침해도 그 글을 연다', () => {
  const 저장소 = 선택저장소();
  const 완료한글 = 테마별지문들.명상[3];
  const 기록 = 시도목록([...시도(테마별지문들.시작하기[1], 8), ...시도(완료한글, 9, true)]);
  마지막지문저장(완료한글.id, 저장소);
  const 다음 = 다음미완료지문(완료한글.id, 기록);
  마지막지문저장(다음.지문.id, 저장소);
  expect(첫진입지문선택(기록, 마지막지문읽기(저장소))).toEqual(다음);
});

it('완료한 글을 다시 선택해도 해당 선택을 기억한다', () => {
  const 저장소 = 선택저장소();
  const 글 = 테마별지문들.명상[3];
  const 기록 = 시도목록(시도(글, 9, true));
  마지막지문저장(글.id, 저장소);
  expect(첫진입지문선택(기록, 마지막지문읽기(저장소))).toEqual({ 테마: '명상', 지문: 글 });
});

it('저장된 선택이 없거나 유효하지 않으면 기존 진행 기록을 사용한다', () => {
  const 저장소 = 선택저장소();
  const 글 = 테마별지문들.명상[3];
  const 기록 = 시도목록(시도(글, 9));
  expect(마지막지문읽기(저장소)).toBeUndefined();
  저장소.setItem(마지막지문저장키, '삭제된 지문');
  expect(마지막지문읽기(저장소)).toBeUndefined();
  expect(마지막지문저장('없는 지문', 저장소)).toBe(false);
  expect(첫진입지문선택(기록, 마지막지문읽기(저장소))).toEqual({ 테마: '명상', 지문: 글 });
  expect(첫진입지문선택(기록, '없는 지문')).toEqual({ 테마: '명상', 지문: 글 });
});

it('저장소 접근이 차단되어도 글 선택을 중단하지 않는다', () => {
  const 저장소 = {
    getItem: () => { throw new Error('접근 차단'); },
    setItem: () => { throw new Error('용량 초과'); },
  };
  expect(마지막지문읽기(저장소)).toBeUndefined();
  expect(마지막지문저장(테마별지문들.시작하기[0].id, 저장소)).toBe(false);
});

it('진행 중인 글이 없으면 최근 완료 글 다음의 첫 미완료 글을 고른다', () => {
  const 지문들 = 테마별지문들.시작하기;
  const 기록 = 시도목록([
    ...시도(지문들[0], 9, true),
    ...시도(지문들[1], 10, true),
    ...시도(지문들[2], 11, true),
  ]);
  expect(첫진입지문선택(기록)).toEqual({ 테마: '시작하기', 지문: 지문들[3] });

  const 시작하기완료 = 시도목록(지문들.flatMap((지문, 순서) => 시도(지문, 순서 + 8, true)));
  expect(첫진입지문선택(시작하기완료))
    .toEqual({ 테마: '산문', 지문: 테마별지문들.산문[0] });
});

it('주제를 누르면 최근 진행 중인 글, 첫 미완료 글, 첫 글 순서로 고른다', () => {
  const 지문들 = 테마별지문들.시작하기;
  const 완료기록 = [...시도(지문들[0], 8, true), ...시도(지문들[2], 9, true)];
  expect(주제지문선택('시작하기', 시도목록(완료기록)).지문).toBe(지문들[1]);

  const 진행기록 = [...완료기록, ...시도(지문들[3], 10), ...시도(지문들[4], 11)];
  expect(주제지문선택('시작하기', 시도목록(진행기록)).지문).toBe(지문들[4]);

  const 전체완료 = 시도목록(지문들.flatMap((지문, 순서) => 시도(지문, 순서 + 8, true)));
  expect(주제지문선택('시작하기', 전체완료).지문).toBe(지문들[0]);
});

it('주제 완료도는 현재 본문 버전에서 한 번이라도 완료한 글만 센다', () => {
  const 지문들 = 테마별지문들.시작하기;
  expect(주제완료현황('시작하기', [])).toEqual({ 완료: 0, 전체: 지문들.length });
  const 기록작업 = [
    ...시도(지문들[0], 8, true),
    ...시도(지문들[1], 9, true, 'old-version'),
    ...시도(지문들[2], 10),
  ];
  const 기록 = 시도목록(기록작업);
  expect(주제완료현황('시작하기', 기록)).toEqual({ 완료: 1, 전체: 지문들.length });
  const 다시쓰기 = 시도목록([...기록작업, ...시도(지문들[0], 11)]);
  expect(주제완료현황('시작하기', 다시쓰기)).toEqual({ 완료: 1, 전체: 지문들.length });
  const 전체완료 = 시도목록(지문들.flatMap((지문, 순서) => 시도(지문, 순서 + 8, true)));
  expect(주제완료현황('시작하기', 전체완료)).toEqual({ 완료: 지문들.length, 전체: 지문들.length });
});

it('즐겨찾기로 모은 글도 최근 진행 중, 첫 미완료, 첫 글 순서로 고른다', () => {
  const 글들 = [테마별지문들.산문[0], 테마별지문들.식물[0], 테마별지문들.우주[0]];
  expect(지문모음선택([], [])).toBeUndefined();
  expect(지문모음선택(글들, [])).toBe(글들[0]);
  const 완료기록 = 시도목록([...시도(글들[0], 8, true), ...시도(글들[1], 9, true)]);
  expect(지문모음선택(글들, 완료기록)).toBe(글들[2]);
  expect(지문모음완료현황(글들, 완료기록)).toEqual({ 완료: 2, 전체: 3 });
  const 진행기록 = 시도목록([...시도(글들[0], 8, true), ...시도(글들[1], 9),
    ...시도(글들[2], 10)]);
  expect(지문모음선택(글들, 진행기록)).toBe(글들[2]);
  const 전부완료 = 시도목록(글들.flatMap((지문, 순서) => 시도(지문, 순서 + 8, true)));
  expect(지문모음선택(글들, 전부완료)).toBe(글들[0]);
});

it('다음 글은 완료한 글을 건너뛰고 다음 주제로 이어진 뒤 처음으로 순환한다', () => {
  const 시작 = 테마별지문들.시작하기;
  const 산문 = 테마별지문들.산문;
  const 기록 = 시도목록([...시도(시작.at(-1)!, 9, true), ...시도(산문[0], 10, true)]);
  expect(다음미완료지문(시작.at(-1)!.id, 기록)).toEqual({ 테마: '산문', 지문: 산문[1] });
  expect(다음미완료지문(테마별지문들.봄봄.at(-1)!.id, 기록))
    .toEqual({ 테마: '시작하기', 지문: 시작[0] });
});

it('모든 글을 완료했다면 첫 진입과 다음 글 모두 시작하기 첫 글로 돌아간다', () => {
  const 전체 = Object.values(테마별지문들).flat();
  const 기록 = 시도목록(전체.flatMap((지문) => 시도(지문, 9, true)));
  const 기본 = { 테마: '시작하기', 지문: 테마별지문들.시작하기[0] };
  expect(첫진입지문선택(기록)).toEqual(기본);
  expect(다음미완료지문(전체.at(-1)!.id, 기록)).toEqual(기본);
});
